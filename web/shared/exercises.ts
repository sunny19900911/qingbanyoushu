function equipmentPriority(equipment: string): number {
  if (equipment.includes("哑铃")) return 0;
  if (equipment.includes("壶铃")) return 1;
  if (equipment.includes("杠铃")) return 2;
  if (/器械|腿举机|绳索/.test(equipment)) return 4;
  return 3;
}

export const EXERCISES: ExerciseItem[] = [...EXERCISE_LIBRARY, ...EXPANDED_EXERCISES]
  .slice()
  .sort((left, right) => equipmentPriority(left.equipment) - equipmentPriority(right.equipment));

export const EXERCISE_CATEGORIES: Array<"全部" | ExerciseItem["bodyPart"]> = [
  "全部", "全身", "下肢", "胸部", "背部", "肩部", "手臂", "核心",
];

export function getExercise(id: string): ExerciseItem | null {
  return EXERCISES.find((item) => item.id === id) ?? null;
}
